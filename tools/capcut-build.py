"""Build a CapCut draft that cuts the scene images on the transcript's own timestamps.

The companion to tools/kdenlive-build.py. Both read the same cut plan from tools/cuts.py,
so a project assembled in CapCut lands on exactly the frames it would in Kdenlive.

CapCut has no timeline import format, so this writes its draft folder directly. Every
object is cloned from a template extracted from a real CapCut draft rather than written
from scratch, because the format is undocumented and the fields that matter are not the
ones that look important.

    python3 tools/capcut-build.py projects/13-the-psychology-of-being-poor \\
        --media-root /Users/htnt/Me/Things/Build-a-Channel

Copy the resulting folder into CapCut's draft directory and it appears in the project
list. The paths inside point at the media on the machine that will open it, which is why
--media-root is required: this repo lives somewhere else on that machine.
"""

