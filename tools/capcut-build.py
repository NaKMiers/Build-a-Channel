def fill(template, draft, project, dest):
    """Substitute into an installer template. Not str.format: these are shell and batch,
    and both are full of braces that format would try to read as fields."""
    return (template.replace("<<DRAFT>>", draft)
                    .replace("<<PROJECT>>", project)
                    .replace("<<DEST>>", dest))


def us(frames, fps):
    """Frames to microseconds. The plan is in frames; CapCut is not."""
    return int(round(frames * 1_000_000 / fps))


def uid():
    return str(uuid.uuid4()).upper()


def join(root, *parts, sep="/"):
    """Path on the machine that will open the draft, not on this one.

    The separator is passed in, never sniffed off the root: the root is a placeholder
    the installer fills in later, so there is no drive letter to read it from.
    """
    return sep.join([root.rstrip("/\\")] + [str(p).replace("/", sep) for p in parts])


def build(args):
    project = Path(args.project).resolve()
    tmpl = json.loads(TEMPLATE.read_text(encoding="utf-8"))

    media_root = MEDIA_TOKEN

    fps = args.fps
    plan = cuts.plan(project, fps, args.allow_gaps, args.audio, args.duration)
    repo = Path(__file__).resolve().parent.parent

    def remote(path):
        """A path the installer will complete, relative to wherever the repo is there."""
        return join(media_root, Path(path).resolve().relative_to(repo), sep=SEP_TOKEN)

    # Canvas follows the scene images, the way CapCut derives it from the first clip.
    size = cuts.image_size(plan.cuts[0][2]) or (1920, 1080)
    width = args.width or 1920
    height = args.height or int(round(width * size[1] / size[0])) // 2 * 2

    now = int(time.time() * 1_000_000)
    now_s = int(time.time())

    materials = {k: [] for k in (
        "videos", "audios", "canvases", "speeds", "placeholder_infos",
        "sound_channel_mappings", "material_colors", "loudnesses",
        "vocal_separations", "beats",
    )}

    def aux(bucket):
        """One private copy of a shared auxiliary material, with a fresh id."""
        obj = copy.deepcopy(tmpl["aux"][bucket])
        obj["id"] = uid()
        materials[bucket].append(obj)
        return obj["id"]

    # draft_meta_info's draft_materials is the Media bin. Leaving it empty leaves the bin
    # empty, which is how a draft that otherwise looks right arrives with nothing to
    # re-drag and every clip reported as not accessible.
    bin_entries = []

    def bin_entry(path, metetype, duration, width, height):
        entry_id = str(uuid.uuid4())
        bin_entries.append({
            "ai_group_type": "", "create_time": now_s, "duration": duration,
            "enter_from": 0, "extra_info": Path(path).name, "file_Path": remote(path),
            "height": height, "id": entry_id, "import_time": now_s,
            "import_time_ms": now, "item_source": 1, "material_color_tag": "",
            "md5": "", "metetype": metetype,
            "roughcut_time_range": ({"duration": duration, "start": 0}
                                    if metetype == "music" else
                                    {"duration": -1, "start": -1}),
            "sub_time_range": {"duration": -1, "start": -1},
            "type": 0, "width": width,
        })
        return entry_id

    def photo(path, name=None):
        obj = copy.deepcopy(tmpl["photo_material"])
        w, h = cuts.image_size(path) or (0, 0)
        obj.update(id=uid(), path=remote(path), width=w, height=h,
                   material_name=name or Path(path).name, duration=STILL_DURATION)
        materials["videos"].append(obj)
        bin_entry(path, "photo", 5_000_000, w, h)
        return obj["id"]

    def video_segment(material_id, start_us, end_us, clip=None, index=0):
        seg = copy.deepcopy(tmpl["video_segment"])
        seg["id"] = uid()
        seg["material_id"] = material_id
        seg["extra_material_refs"] = [aux(b) for b in tmpl["video_ref_order"]]
        span = {"start": start_us, "duration": end_us - start_us}
        seg["target_timerange"] = dict(span)
        seg["source_timerange"] = {"start": 0, "duration": span["duration"]}
        seg["render_index"] = index
        seg["track_render_index"] = index
        if clip:
            seg["clip"] = clip
        return seg

    # V1: one segment per scene, each held until the next cue. Every boundary is taken
    # from the microsecond position of the next cue, never from a separately rounded
    # duration: round(a) + round(b) is not round(a + b), and at 30fps a frame is
    # 33333.33us, so rounding each duration on its own leaves a gap at most boundaries.
    bounds = [us(start, fps) for start, _, _ in plan.cuts] + [us(plan.total_frames, fps)]
    scene_segments = [
        video_segment(photo(path), bounds[i], bounds[i + 1], index=i)
        for i, (_, _, path) in enumerate(plan.cuts)
    ]

    tracks = []
    v1 = copy.deepcopy(tmpl["video_track"])
    v1.update(id=uid(), segments=scene_segments)
    tracks.append(v1)

    # V2: the logo, held over the whole video, placed by normalised offset from centre.
    if args.logo:
        logo = Path(args.logo).resolve()
        if not logo.exists():
            raise SystemExit(f"no logo at {logo}")
        lw, lh = cuts.image_size(logo) or (1, 1)
        x, y, w, h = cuts.logo_box(width, height, args.logo_size,
                                   args.logo_right, args.logo_bottom)
        # CapCut fits the image to the canvas first, then applies scale, so a scale of 1
        # is already the fitted size and not the source pixels. Confirmed against a real
        # draft: scale 0.07092 on a 1254px logo in a 1920x1072 canvas renders 76px.
        fit = min(width / lw, height / lh)
        clip = copy.deepcopy(tmpl["video_segment"]["clip"])
        clip["scale"] = {"x": w / (lw * fit), "y": w / (lw * fit)}
        # transform is the centre, normalised to -1..1 from the middle of the frame.
        clip["transform"] = {
            "x": ((x + w / 2) - width / 2) / (width / 2),
            "y": -(((y + h / 2) - height / 2) / (height / 2)),
        }
        v2 = copy.deepcopy(tmpl["video_track"])
        v2.update(id=uid(), flag=2, segments=[
            video_segment(photo(logo), 0, bounds[-1], clip=clip)
        ])
        tracks.append(v2)

    # A1: the narration, one segment running the whole timeline.
    audio_mat = copy.deepcopy(tmpl["audio_material"])
    audio_seconds = cuts.audio_seconds(plan.audio)
    audio_us = int(round(audio_seconds * 1_000_000))
    audio_mat.update(id=uid(), path=remote(plan.audio), name=plan.audio.name,
                     duration=audio_us, music_id=str(uuid.uuid4()),
                     local_material_id=bin_entry(plan.audio, "music", audio_us, 0, 0))
    materials["audios"].append(audio_mat)

    a_seg = copy.deepcopy(tmpl["audio_segment"])
    a_seg["id"] = uid()
    a_seg["material_id"] = audio_mat["id"]
    a_seg["extra_material_refs"] = [aux(b) for b in tmpl["audio_ref_order"]]
    span = {"start": 0, "duration": bounds[-1]}
    a_seg["target_timerange"] = dict(span)
    a_seg["source_timerange"] = dict(span)
    a1 = copy.deepcopy(tmpl["audio_track"])
    a1.update(id=uid(), segments=[a_seg])
    tracks.append(a1)

    timeline_id, draft_id, project_id = uid(), uid(), uid()

    doc = copy.deepcopy(tmpl["document"])
    doc.update(
        id=timeline_id,
        duration=bounds[-1],
        fps=float(fps),
        canvas_config={"ratio": "original", "width": width, "height": height,
                       "background": None},
        materials={**doc.get("materials", {}), **materials},
        tracks=tracks,
        create_time=now,
        update_time=now,
        name="",
        path="",
    )
    for empty in ("keyframes", "keyframe_graph_list", "relationships", "time_marks"):
        if empty in doc and isinstance(doc[empty], list):
            doc[empty] = []

    name = args.name or project.name
    # One subfolder per target machine: the media paths inside a draft are absolute
    # and OS specific, so a mac draft and a windows draft are different files.
    out = Path(args.out).resolve() if args.out else project / "edit" / "capcut" / name
    if out.exists() and not args.force and not args.dry_run:
        raise SystemExit(
            f"{out} already exists. A draft opened in CapCut holds hand work no rebuild\n"
            f"can recover, so pass --force to overwrite or --out to write another."
        )

    if args.dry_run:
        for start, length, path in plan.cuts:
            print(f"{cuts.tc(start, fps)}  {length:5d}f  {length / fps:6.2f}s  {path.name}")
        print(f"\n{len(plan)} scenes, {cuts.tc(plan.total_frames, fps)} total, {fps} fps, "
              f"{width}x{height}")
        for line in plan.report:
            print(f"note: {line}")
        print(f"would write {out}")
        return

    draft_root = args.draft_root or DRAFT_TOKEN
    fold = join(draft_root, name, sep=SEP_TOKEN)
    meta = {
        "draft_cover": "draft_cover.jpg",
        "draft_fold_path": fold,
        "draft_id": draft_id,
        "draft_name": name,
        "draft_root_path": draft_root,
        "draft_removable_storage_device": "",
        "draft_timeline_materials_size_": 0,
        "draft_type": "",
        "tm_draft_create": now,
        "tm_draft_modified": now,
        "tm_draft_removed": 0,
        "tm_duration": doc["duration"],
        "draft_materials": [{"type": 0, "value": bin_entries}]
                           + [{"type": t, "value": []} for t in (1, 2, 3, 6, 7, 8)],
        "draft_materials_copied_info": [],
        "draft_segment_extra_info": [],
        "draft_enterprise_info": {"draft_enterprise_extra": "",
                                  "draft_enterprise_id": "",
                                  "draft_enterprise_name": "",
                                  "enterprise_material": []},
        "draft_is_ai_shorts": False,
        "draft_is_invisible": False,
        "draft_new_version": "",
    }

    out.mkdir(parents=True, exist_ok=True)
    (out / "Timelines" / timeline_id).mkdir(parents=True, exist_ok=True)
    body = json.dumps(doc, ensure_ascii=False)
    # CapCut keeps the timeline in both places and they are byte-identical.
    (out / "draft_info.json").write_text(body, encoding="utf-8")
    (out / "Timelines" / timeline_id / "draft_info.json").write_text(body, encoding="utf-8")
    (out / "draft_meta_info.json").write_text(json.dumps(meta, ensure_ascii=False),
                                              encoding="utf-8")
    (out / "Timelines" / "project.json").write_text(json.dumps({
        "config": {"color_space": -1, "mixed_track_mode_on": False,
                   "render_index_track_mode_on": False, "use_float_render": False},
        "create_time": now, "id": project_id, "main_timeline_id": timeline_id,
        "timelines": [{"create_time": now, "id": timeline_id, "is_marked_delete": False,
                       "name": "Timeline 01", "update_time": now}],
        "update_time": now, "version": 0,
    }, ensure_ascii=False), encoding="utf-8")

    # Both launchers beside the draft, never inside it: anything inside would be copied
    # into CapCut's own folder along with the timeline. The draft itself is the same file
    # on either machine, so there is one of it and two ways to install it.
    rel = str(project.relative_to(repo))
    mac = out.parent / "install-mac.command"
    mac.write_text(
        fill(MAC_INSTALLER, json.dumps(name), json.dumps(rel),
             json.dumps(args.draft_root or DRAFT_ROOT_VARS["mac"])),
        encoding="utf-8")
    mac.chmod(0o755)
    win = out.parent / "install-windows.bat"
    win.write_text(
        fill(WINDOWS_INSTALLER, name, rel.replace("/", "\\"),
             (args.draft_root or DRAFT_ROOT_VARS["windows"]).replace("/", "\\")),
        encoding="utf-8", newline="\r\n")

    print(out)
    print(f"  {mac.name} installs it on a Mac, {win.name} on Windows")
    print(f"  {len(plan)} scenes" + (", logo" if args.logo else "")
          + f", narration, {cuts.tc(plan.total_frames, fps)} at {fps} fps, {width}x{height}")
    print("  paths resolve from wherever the repo sits on that machine")
    for line in plan.report:
        print(f"  note: {line}")


def main():
    p = argparse.ArgumentParser(
        description="Cut a project's scene images onto a CapCut timeline at their "
                    "transcript times.")
    p.add_argument("project", help="projects/<n>-<slug>")
    p.add_argument("--draft-root", help="CapCut draft directory on that machine")
    p.add_argument("--name", help="draft name, and the folder name (default the project)")
    p.add_argument("--out", help="where to write the draft folder locally")
    p.add_argument("--audio", help="narration file (default <project>/audios/full.mp3)")
    p.add_argument("--duration", type=float, help="override the narration length")
    p.add_argument("--fps", type=int, default=30)
